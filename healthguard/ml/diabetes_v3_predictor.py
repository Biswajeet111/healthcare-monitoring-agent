"""Versioned diabetes screening inference service.

HealthGuard AI — Experimental Diabetes Model v3

This module provides:
- Model artifact loading
- Metadata consistency validation
- Patient input validation
- Versioned diabetes screening inference
- Typed exceptions for API integration

IMPORTANT:
This model is experimental and is not clinically validated.
Its predictions must not be used for medical diagnosis.
"""

import json
from functools import lru_cache
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
from sklearn.linear_model import LogisticRegression
from sklearn.pipeline import Pipeline
from healthguard.ml.model_integrity import (
    ModelIntegrityError,
    verify_model_integrity,
)

# ============================================================
# 1. CONFIGURATION
# ============================================================

ROOT = Path(__file__).resolve().parents[2]

MODEL_DIR = ROOT / "models" / "diabetes_v3_candidate"

MODEL_PATH = MODEL_DIR / "pipeline.joblib"

try:
    verify_model_integrity(MODEL_PATH)

except ModelIntegrityError as exc:
    raise DiabetesModelError(
        "Diabetes v3 model integrity verification failed"
    ) from exc

METADATA_PATH = MODEL_DIR / "metadata.json"

MODEL_VERSION = "experimental-v3-candidate"

MODEL_NAME = "LogisticRegression"

THRESHOLD = 0.30

FEATURE_NAMES = [
    "Pregnancies",
    "Glucose",
    "BloodPressure",
    "SkinThickness",
    "Insulin",
    "BMI",
    "DiabetesPedigreeFunction",
    "Age",
]

REQUIRED_POSITIVE = [
    "Glucose",
    "BloodPressure",
    "SkinThickness",
    "Insulin",
    "BMI",
]
FEATURE_LIMITS = {
    "Pregnancies": (0, 25),
    "Glucose": (0, 600),
    "BloodPressure": (0, 250),
    "SkinThickness": (0, 100),
    "Insulin": (0, 1000),
    "BMI": (0, 100),
    "DiabetesPedigreeFunction": (0, 5),
    "Age": (1, 120),
}


# ============================================================
# 2. CUSTOM EXCEPTIONS
# ============================================================

class DiabetesInputError(ValueError):
    """Raised when patient input is invalid."""


class DiabetesModelError(RuntimeError):
    """Raised when the model or its configuration is invalid."""


# ============================================================
# 3. METADATA VALIDATION
# ============================================================

def validate_model_metadata(metadata: dict):
    """Validate the saved model configuration."""

    if not isinstance(metadata, dict):
        raise DiabetesModelError(
            "Model metadata must be a JSON object"
        )

    if metadata.get("model_version") != MODEL_VERSION:
        raise DiabetesModelError(
            "Model version mismatch"
        )

    if metadata.get("model") != MODEL_NAME:
        raise DiabetesModelError(
            "Model type mismatch"
        )

    if metadata.get("feature_names") != FEATURE_NAMES:
        raise DiabetesModelError(
            "Model feature configuration mismatch"
        )

    threshold = metadata.get("threshold")

    if (
        isinstance(threshold, bool)
        or not isinstance(threshold, (int, float))
        or not np.isfinite(threshold)
        or not np.isclose(threshold, THRESHOLD, rtol=0, atol=1e-12)
    ):
        raise DiabetesModelError(
            "Model threshold mismatch"
        )

    return True


# ============================================================
# 4. MODEL LOADING
# ============================================================

@lru_cache(maxsize=1)
def load_v3_model():
    """Load and validate the frozen experimental model."""

    if not MODEL_PATH.is_file():
        raise DiabetesModelError(
            "Diabetes v3 model artifact is unavailable"
        )

    if not METADATA_PATH.is_file():
        raise DiabetesModelError(
            "Diabetes v3 metadata is unavailable"
        )

    # Read model metadata.
    try:
        with METADATA_PATH.open(
            "r",
            encoding="utf-8",
        ) as file:
            metadata = json.load(file)

    except (OSError, ValueError) as exc:
        raise DiabetesModelError(
            "Unable to read diabetes v3 metadata"
        ) from exc

    # Validate saved configuration.
    validate_model_metadata(metadata)

    # IMPORTANT:
    # joblib uses pickle internally.
    # Only load trusted model artifacts generated by this project.
    try:
        pipeline = joblib.load(MODEL_PATH)

    except Exception as exc:
        raise DiabetesModelError(
            "Unable to load diabetes v3 model"
        ) from exc

    # Validate pipeline type.
    if not isinstance(pipeline, Pipeline):
        raise DiabetesModelError(
            "Invalid model pipeline"
        )

    expected_steps = [
        "preprocessing",
        "scaler",
        "classifier",
    ]

    actual_steps = list(pipeline.named_steps.keys())

    if actual_steps != expected_steps:
        raise DiabetesModelError(
            "Unexpected model pipeline structure"
        )

    # Validate classifier.
    classifier = pipeline.named_steps["classifier"]

    if not isinstance(classifier, LogisticRegression):
        raise DiabetesModelError(
            "Unexpected classifier in model artifact"
        )

    # Validate prediction capabilities.
    if not hasattr(pipeline, "predict_proba"):
        raise DiabetesModelError(
            "Model does not support probability scores"
        )

    if not hasattr(classifier, "classes_"):
        raise DiabetesModelError(
            "Classifier has not been fitted"
        )

    if list(classifier.classes_) != [0, 1]:
        raise DiabetesModelError(
            "Unexpected model classes"
        )

    # Validate expected feature configuration.
    if hasattr(pipeline, "feature_names_in_"):
        if list(pipeline.feature_names_in_) != FEATURE_NAMES:
            raise DiabetesModelError(
                "Saved pipeline feature order mismatch"
            )

    return pipeline


# ============================================================
# 5. PATIENT INPUT VALIDATION
# ============================================================

def validate_features(features: dict):
    """Validate patient measurements before model inference."""

    if not isinstance(features, dict):
        raise DiabetesInputError(
            "Features must be a dictionary"
        )

    missing = set(FEATURE_NAMES) - set(features)

    extra = set(features) - set(FEATURE_NAMES)

    if missing:
        raise DiabetesInputError(
            f"Missing features: {sorted(missing)}"
        )

    if extra:
        raise DiabetesInputError(
            f"Unexpected features: {sorted(extra)}"
        )

    values = []

    for name in FEATURE_NAMES:

        value = features[name]

        # Reject boolean values.
        if isinstance(value, (bool, np.bool_)):
            raise DiabetesInputError(
                f"{name} must be a numerical value"
            )

        # Convert to float.
        try:
            number = float(value)

        except (TypeError, ValueError, OverflowError) as exc:
            raise DiabetesInputError(
                f"{name} must be a numerical value"
            ) from exc

        # Reject NaN and infinity.
        if not np.isfinite(number):
            raise DiabetesInputError(
                f"{name} must be finite"
            )
        minimum, maximum = FEATURE_LIMITS[name]

        if not minimum <= number <= maximum:
            raise DiabetesInputError(
            f"{name} must be between {minimum} and {maximum}"
            )


        # Certain measurements cannot be zero
        # for this experimental inference endpoint.
        if name in REQUIRED_POSITIVE and number == 0:
            raise DiabetesInputError(
                f"{name} must be greater than zero "
                "for this inference endpoint"
            )


        # Enforce integer-valued count fields.
        if name == "Pregnancies" and not number.is_integer():
            raise DiabetesInputError(
                "Pregnancies must be an integer"
            )

        if name == "Age" and not number.is_integer():
            raise DiabetesInputError(
                "Age must be an integer"
            )

        values.append(number)

    # Maintain the exact feature order used during training.
    return pd.DataFrame(
        [values],
        columns=FEATURE_NAMES,
    )


# ============================================================
# 6. DIABETES PREDICTION
# ============================================================

def predict_diabetes_v3(features: dict):
    """Run experimental diabetes screening inference."""

    # Validate patient input.
    input_df = validate_features(features)

    # Load frozen model.
    pipeline = load_v3_model()

    # Generate model score.
    try:
        probabilities = pipeline.predict_proba(input_df)

        score = float(probabilities[0][1])

    except Exception as exc:
        raise DiabetesModelError(
            "Diabetes v3 inference failed"
        ) from exc

    # Validate model output.
    if not np.isfinite(score):
        raise DiabetesModelError(
            "Model returned an invalid score"
        )

    if not 0 <= score <= 1:
        raise DiabetesModelError(
            "Model score is outside the expected range"
        )

    # Apply experimental decision threshold.
    prediction = int(score >= THRESHOLD)

    screening_result = (
        "Positive model classification"
        if prediction == 1
        else "Negative model classification"
    )

    # Return consistent API-ready response.
    return {
        "prediction": prediction,
        "model_score": round(score, 4),
        "screening_result": screening_result,
        "model": MODEL_NAME,
        "model_version": MODEL_VERSION,
        "threshold": THRESHOLD,
        "disclaimer": (
            "This is an experimental machine learning "
            "screening result, not a medical diagnosis. "
            "The model has not been clinically validated "
            "and its score is not a clinically established "
            "probability of diabetes. A negative result "
            "does not rule out diabetes. Consult a "
            "qualified healthcare professional."
        ),
    }